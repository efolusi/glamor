#!/usr/bin/env python3
"""Writes <lang>.lproj/Localizable.strings next to each String Catalog (Localizable.xcstrings).

SwiftPM compiles a .xcstrings only with some toolchains and build systems: macos-26 CI (Swift 6.3.3, the native
build system) copied the catalog as it was, and every lookup returned its key. The .strings files build the same
everywhere, so they are what the targets ship. The catalog stays the one place words are written.

Usage: scripts/generate-strings.py           # write the files
       scripts/generate-strings.py --check   # exit 1 when a file differs (LocalisationTests runs the same comparison)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOGS = [ROOT / "Sources/Glamor/Resources/Localizable.xcstrings", ROOT / "Sources/GlamorGallery/Resources/Localizable.xcstrings"]
LANGUAGES = ["en", "id"]


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def fail(path, key, why):
    sys.exit("%s: %s %s" % (path.relative_to(ROOT), key, why))


def unit_of(path, key, entry, language):
    """The translated string unit of `key` in `language`, or a stop that names the key. Plurals and device
    variations are not used here (Indonesian has one plural form); a catalog that adds them needs this script extended."""
    loc = entry.get("localizations", {}).get(language)
    if loc is None:
        fail(path, key, "has no %s text" % language)
    if "variations" in loc or "substitutions" in loc:
        fail(path, key, "has a plural or device variation in %s; scripts/generate-strings.py does not write those" % language)
    unit = loc.get("stringUnit")
    if unit is None or unit.get("state") != "translated" or not unit.get("value"):
        fail(path, key, "is not a translated %s string (state %r)" % (language, (unit or {}).get("state")))
    return unit


def render(path, catalog, language):
    lines = ["/* Generated by scripts/generate-strings.py from Localizable.xcstrings. Do not edit. */", ""]
    for key in sorted(catalog["strings"]):
        entry = catalog["strings"][key]
        unit = unit_of(path, key, entry, language)
        if entry.get("comment"):
            lines.append("/* " + entry["comment"].replace("*/", "* /") + " */")
        lines.append('"%s" = "%s";' % (escape(key), escape(unit["value"])))
        lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path in CATALOGS:
        catalog = json.loads(path.read_text(encoding="utf-8"))
        for language in LANGUAGES:
            target = path.parent / (language + ".lproj") / "Localizable.strings"
            want = render(path, catalog, language)
            have = target.read_text(encoding="utf-8") if target.exists() else None
            if have == want:
                continue
            stale.append(str(target.relative_to(ROOT)))
            if not check:
                target.parent.mkdir(exist_ok=True)
                target.write_text(want, encoding="utf-8")
    if stale and check:
        print("out of date, run scripts/generate-strings.py:\n  " + "\n  ".join(stale))
        sys.exit(1)
    print(("checked" if check else "wrote") + " %d catalogs x %d languages" % (len(CATALOGS), len(LANGUAGES)))


if __name__ == "__main__":
    main()
